package gen

import (
	"fmt"
	"math"
	"math/rand/v2"
	"strconv"

	"github.com/breskos/recoant-data/synthetic"
)

func factors(rng *rand.Rand, n, rank int, std float64) [][]float64 {
	out := make([][]float64, n)
	for i := range out {
		v := make([]float64, rank)
		for k := range v {
			v[k] = rng.NormFloat64() * std
		}
		out[i] = v
	}
	return out
}

func dot(a, b []float64) float64 {
	var s float64
	for i := range a {
		s += a[i] * b[i]
	}
	return s
}

func factorTable(name, idCol, prefix string, bias []float64, fs [][]float64) Table {
	rank := len(fs[0])
	t := Table{Name: name, Header: []string{idCol, "bias"}}
	for k := range rank {
		t.Header = append(t.Header, "f"+strconv.Itoa(k+1))
	}
	for i, v := range fs {
		row := []string{id(prefix, i), f(bias[i], 4)}
		for _, x := range v {
			row = append(row, f(x, 4))
		}
		t.Rows = append(t.Rows, row)
	}
	return t
}

// ExplicitRatings is a Netflix-Prize-like set of star ratings generated by
// a low-rank model with biases.
func ExplicitRatings() *Set {
	const (
		users, movies, rank           = 3000, 1500, 10
		mu, userBias, itemBias, noise = 3.6, 0.3, 0.4, 0.5
	)
	rng := newRand(3)
	// Factor std so that the interaction term u·v has a std of about 0.8.
	std := math.Sqrt(0.8 / math.Sqrt(rank))
	uf, mf := factors(rng, users, rank, std), factors(rng, movies, rank, std)
	bu, bm := make([]float64, users), make([]float64, movies)
	for i := range bu {
		bu[i] = rng.NormFloat64() * userBias
	}
	for i := range bm {
		bm[i] = rng.NormFloat64() * itemBias
	}
	perm := rng.Perm(movies)
	z := newZipf(rng, 0.8, movies)
	e := &emitter{rng: rng}
	for u := range users {
		n := min(20+int(rng.ExpFloat64()*30), 300)
		seen := make(map[int]bool, n)
		for tries := 0; len(seen) < n && tries < 20*n; tries++ {
			m := perm[z.draw()]
			if seen[m] {
				continue
			}
			seen[m] = true
			r := mu + bu[u] + bm[m] + dot(uf[u], mf[m]) + noise*rng.NormFloat64()
			r = math.Max(1, math.Min(5, math.Round(r)))
			e.emit("user", id("u", u), "movie", id("m", m), "rating", r, randTime(rng, Start, 180*day), "")
		}
	}
	sortByTime(e.out)
	return &Set{
		Meta: synthetic.Dataset{
			Name: "latent/explicit-ratings", Folder: "latent", Ordered: true,
			Description: fmt.Sprintf("Star ratings (1–5) of %d users for %d movies over 180 days, like the Netflix Prize. Generated as round(μ + b_u + b_m + p_u·q_m + ε) clipped to 1–5, with μ = %.1f, user biases N(0, %.1f), movie biases N(0, %.1f), rank-%d factors and noise N(0, %.1f). Users rate 20 to 300 movies, chosen with a Zipf popularity bias.", users, movies, mu, userBias, itemBias, rank, noise),
			Expected:    "Matrix factorization (Funk-SVD, biased MF, SVD++) and truncated SVD/PCA should recover the rank-10 structure: on this data the true model has an RMSE of 0.55 (noise and rounding), the true biases alone 0.91 and the global mean 1.01. A learned model between 0.55 and 0.91 captures latent structure; the closer to 0.55 the better. users.csv and movies.csv hold the true biases and factors (f1–f10).",
		},
		Signals: e.out,
		Tables: []Table{
			factorTable("users.csv", "user_id", "u", bu, uf),
			factorTable("movies.csv", "movie_id", "m", bm, mf),
		},
	}
}

// ImplicitFeedback is generated by a low-rank model: users pick items with
// probability ∝ exp(score / τ) and go deeper into the funnel for better
// matches.
func ImplicitFeedback() *Set {
	const (
		users, items, rank, per = 4000, 2000, 8, 30
		temp                    = 0.5
	)
	rng := newRand(4)
	std := math.Sqrt(1 / math.Sqrt(rank))
	uf, itf := factors(rng, users, rank, std), factors(rng, items, rank, std)
	bu, bi := make([]float64, users), make([]float64, items)
	for i := range bi {
		bi[i] = rng.NormFloat64() * 0.5
	}
	e := &emitter{rng: rng}
	w := make([]float64, items)
	score := make([]float64, items)
	for u := range users {
		for i := range items {
			score[i] = dot(uf[u], itf[i]) + bi[i]
			w[i] = math.Exp(score[i] / temp)
		}
		c := newCategorical(w)
		for range per {
			i := c.draw(rng)
			p := 1 / (1 + math.Exp(-score[i])) // affinity in (0, 1)
			fn := funnel{click: 0.2 + 0.7*p, dwellMu: math.Log(10 + 80*p), dwellSig: 0.6, cart: 0.05 + 0.4*p, purchase: 0.3 + 0.5*p}
			e.interact(id("u", u), "item", id("i", i), randTime(rng, Start, 60*day), fn, "")
		}
	}
	sortByTime(e.out)
	return &Set{
		Meta: synthetic.Dataset{
			Name: "latent/implicit-feedback", Folder: "latent", Ordered: true,
			Description: fmt.Sprintf("%d users, %d items, %d interactions per user over 60 days. A user picks item i with probability ∝ exp((p_u·q_i + b_i) / %.1f) with rank-%d factors and item biases N(0, 0.5). Better matches go deeper into the funnel: click, dwell time, cart and purchase rise with the affinity σ(p_u·q_i + b_i).", users, items, per, temp, rank),
			Expected:    "The set for implicit-feedback models: ALS (with confidence from signal strength), BPR and item-kNN should clearly beat popularity. Weighting deep signals (purchase, long dwell) higher than visits should help, because depth carries affinity. users.csv and items.csv hold the true factors (user bias is 0).",
		},
		Signals: e.out,
		Tables: []Table{
			factorTable("users.csv", "user_id", "u", bu, uf),
			factorTable("items.csv", "item_id", "i", bi, itf),
		},
	}
}
