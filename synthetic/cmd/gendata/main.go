// Command gendata writes all synthetic data sets, catalog.go and README.md.
//
//	go run ./cmd/gendata -out .
package main

import (
	"bufio"
	"compress/gzip"
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/breskos/recoant-data/synthetic"
	"github.com/breskos/recoant-data/synthetic/internal/gen"
)

func main() {
	out := flag.String("out", ".", "output folder (the synthetic module)")
	only := flag.String("only", "", "generate only data sets whose name contains this text; catalog and README are not rewritten")
	flag.Parse()
	if err := run(*out, *only, gen.All(), log.Printf); err != nil {
		log.Fatal(err)
	}
}

// run writes the data sets of gens whose name contains only (all if
// empty) below out, and with all of them catalog.go and README.md.
func run(out, only string, gens []func() *gen.Set, logf func(string, ...any)) error {
	var metas []synthetic.Dataset
	for _, g := range gens {
		s := g()
		if only != "" && !strings.Contains(s.Meta.Name, only) {
			continue
		}
		m, err := write(out, s)
		if err != nil {
			return err
		}
		logf("%-28s %9d signals", m.Name, m.Signals.Rows)
		metas = append(metas, m)
	}
	if only != "" {
		return nil
	}
	if err := writeFile(filepath.Join(out, "catalog.go"), func(w io.Writer) error { return catalog(w, metas) }); err != nil {
		return err
	}
	return writeFile(filepath.Join(out, "README.md"), func(w io.Writer) error { return readme(w, metas) })
}

func write(root string, s *gen.Set) (synthetic.Dataset, error) {
	m := s.Meta
	dir := filepath.Join(root, filepath.FromSlash(m.Name))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return m, err
	}
	name := "signals.csv"
	if s.Gzip {
		name += ".gz"
	}
	var rows [][]string
	if m.Invalid {
		rows = gen.InvalidRows
	} else {
		for _, x := range s.Signals {
			rows = append(rows, x.Record())
		}
		m.SubjectKinds, m.ObjectKinds, m.Types = kinds(s.Signals)
	}
	m.Signals = synthetic.File{Name: name, Rows: len(rows), Header: synthetic.SignalHeader}
	if err := writeCSV(filepath.Join(dir, name), s.Gzip, synthetic.SignalHeader, rows); err != nil {
		return m, err
	}
	for _, t := range s.Tables {
		if err := writeCSV(filepath.Join(dir, t.Name), false, t.Header, t.Rows); err != nil {
			return m, err
		}
		m.Tables = append(m.Tables, synthetic.File{Name: t.Name, Rows: len(t.Rows), Header: t.Header})
	}
	return m, nil
}

func kinds(s []synthetic.Signal) (subjects, objects, types []string) { return gen.Kinds(s) }

func writeCSV(path string, gz bool, header []string, rows [][]string) error {
	return writeFile(path, func(w io.Writer) error { return encodeCSV(w, gz, header, rows) })
}

// encodeCSV writes the header and rows to w, gzip-compressed if gz.
func encodeCSV(w io.Writer, gz bool, header []string, rows [][]string) error {
	if !gz {
		return writeRows(w, header, rows)
	}
	z, _ := gzip.NewWriterLevel(w, gzip.BestCompression) // a valid level never fails
	z.ModTime = gen.Start                                // reproducible output
	return errors.Join(writeRows(z, header, rows), z.Close())
}

func writeRows(w io.Writer, header []string, rows [][]string) error {
	cw := csv.NewWriter(w)
	_ = cw.Write(header) // a write error is sticky; WriteAll reports it
	return cw.WriteAll(rows)
}

func writeFile(path string, fn func(io.Writer) error) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	bw := bufio.NewWriterSize(f, 1<<20)
	err = fn(bw)
	if err == nil {
		err = bw.Flush()
	}
	return errors.Join(err, f.Close())
}

func quoteList(l []string) string {
	q := make([]string, len(l))
	for i, s := range l {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func file(f synthetic.File) string {
	return fmt.Sprintf("{Name: %q, Rows: %d, Header: %s}", f.Name, f.Rows, quoteList(f.Header))
}

func catalog(w io.Writer, ds []synthetic.Dataset) error {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/gendata. DO NOT EDIT.\n\npackage synthetic\n\n// Datasets lists every data set in this folder, grouped by purpose.\nvar Datasets = []Dataset{\n")
	for _, d := range ds {
		fmt.Fprintf(&b, "\t{\n\t\tName:        %q,\n\t\tFolder:      %q,\n\t\tDescription: %q,\n\t\tExpected:    %q,\n", d.Name, d.Folder, d.Description, d.Expected)
		fmt.Fprintf(&b, "\t\tSignals:     File%s,\n", file(d.Signals))
		if len(d.Tables) > 0 {
			b.WriteString("\t\tTables: []File{\n")
			for _, t := range d.Tables {
				fmt.Fprintf(&b, "\t\t\t%s,\n", file(t))
			}
			b.WriteString("\t\t},\n")
		}
		if !d.Invalid {
			fmt.Fprintf(&b, "\t\tSubjectKinds: %s,\n\t\tObjectKinds:  %s,\n\t\tTypes:        %s,\n", quoteList(d.SubjectKinds), quoteList(d.ObjectKinds), quoteList(d.Types))
		}
		if d.Ordered {
			b.WriteString("\t\tOrdered: true,\n")
		}
		if d.Invalid {
			b.WriteString("\t\tInvalid: true,\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err == nil {
		_, err = w.Write(src)
	}
	return err
}

var folders = []struct{ name, purpose string }{
	{"basic", "Batch recommendation with users and items: the baseline (pure popularity) and the standard set for personalized models (taste clusters)."},
	{"latent", "Data generated by low-rank models, for SVD/PCA, matrix factorization, ALS and BPR. The true factors are included."},
	{"funnel", "Signals of different depth and informativeness, for funnel modeling and learning signal relevance."},
	{"stream", "Streams to read in order, for online and incremental learning: trends, new items and preference drift."},
	{"session", "Anonymous sessions, for session-based and next-item recommendation."},
	{"relations", "User–user and entity–entity relations, for user-to-user recommendations and graph models."},
	{"attributes", "Users and entities with attributes (schema.csv) that change over time as events (attributes.csv), for filters, mutual preferences, deletion and retention."},
	{"matching", "Two-sided markets where both sides decide, for reciprocal matching: the target is mutual likes, not likes."},
	{"segments", "Customers in hidden segments defined by behavior and attributes together, for clustering and profiles; the true segments are included."},
	{"loading", "Edge cases and invalid rows for loaders and ingestion."},
	{"benchmark", "Large files for performance measurements."},
}

func readme(w io.Writer, ds []synthetic.Dataset) error {
	var b strings.Builder
	b.WriteString(`# Synthetic data sets for recoant

<!-- Generated by cmd/gendata. DO NOT EDIT. -->

All data in this folder is generated; it contains no third-party and no personal data. Every data set has a known structure, and most come with tables of that hidden structure (clusters, latent factors, item quality, intents, …), so you can tell how well a recommender should do.

## Format

Every data set is a folder with a signals file and optional tables, all CSV with a header row.

` + "`signals.csv`" + ` (or ` + "`signals.csv.gz`" + `) has one signal per row:

| Column | Meaning |
| --- | --- |
| time | RFC 3339 timestamp |
| subject_kind, subject_id | who acted, usually ` + "`user`" + ` |
| object_kind, object_id | what was acted on: an item, product, movie, article or another user |
| type | signal type: visit, click, dwell, cart, purchase, rating, share, follow, … |
| value | magnitude: dwell time in seconds, star rating, quantity; 1 otherwise |
| session | session ID, may be empty |

Signals map one to one onto ` + "`recoant.Signal`" + `. Signals files marked *ordered* are sorted by time; read streams in this order.

Data sets with attributes add ` + "`schema.csv`" + ` (kind, attribute, type, sensitive; types category, number, set, geo) and ` + "`attributes.csv`" + `, a stream of attribute events sorted by time:

| Column | Meaning |
| --- | --- |
| time | RFC 3339 timestamp |
| kind, id | the entity |
| op | ` + "`set`" + ` (also to update) or ` + "`delete`" + ` |
| attribute | the attribute; empty with ` + "`delete`" + ` deletes the whole entity |
| value | category as is, number, set elements joined by ` + "`|`" + `, geo as ` + "`lat,lon`" + `; empty with ` + "`delete`" + ` |

Apply attribute events before signals of the same time.

## Data sets

| Folder | Purpose |
| --- | --- |
`)
	for _, f := range folders {
		fmt.Fprintf(&b, "| [%s](#%s) | %s |\n", f.name, f.name, f.purpose)
	}
	for _, f := range folders {
		fmt.Fprintf(&b, "\n### %s\n", f.name)
		for _, d := range ds {
			if d.Folder != f.name {
				continue
			}
			fmt.Fprintf(&b, "\n#### [%s](%s)\n\n%s\n\n**Expected:** %s\n\n", d.Name, d.Name, d.Description, d.Expected)
			order := ""
			if d.Ordered {
				order = ", ordered by time"
			}
			fmt.Fprintf(&b, "- `%s`: %d signals%s", d.Signals.Name, d.Signals.Rows, order)
			if len(d.Types) > 0 {
				fmt.Fprintf(&b, "; types %s; subjects %s; objects %s", strings.Join(d.Types, ", "), strings.Join(d.SubjectKinds, ", "), strings.Join(d.ObjectKinds, ", "))
			}
			b.WriteString("\n")
			for _, t := range d.Tables {
				fmt.Fprintf(&b, "- `%s`: %d rows; columns %s\n", t.Name, t.Rows, strings.Join(t.Header, ", "))
			}
		}
	}
	b.WriteString(`
## Read the data in Go

This folder is a Go module (` + "`github.com/breskos/recoant-data/synthetic`" + `, standard library only, no dependency on recoant). [catalog.go](catalog.go) lists every data set with its files, [synthetic.go](synthetic.go) reads them, [example_test.go](example_test.go) shows how, and [synthetic_test.go](synthetic_test.go) checks every file against the catalog and its hidden structure:

` + "```" + `
go test ./...
` + "```" + `

## Regenerate

The generators are in [internal/gen](internal/gen). The same seed produces identical files:

` + "```" + `
go run ./cmd/gendata -out .
` + "```" + `
`)
	_, err := io.WriteString(w, b.String())
	return err
}
